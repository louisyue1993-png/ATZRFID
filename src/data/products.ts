// Helper functions - updated to fetch from database
export async function getProductById(id: string): Promise<Product | null> {
  try {
    // Build absolute URL for server-side fetch
    const baseUrl = process.env.NEXT_PUBLIC_BASE_URL || 'http://localhost:5000';
    const url = `${baseUrl}/api/products/${id}`;
    
    const response = await fetch(url, {
      cache: 'no-store' // Ensure we get fresh data
    });
    
    if (!response.ok) {
      console.error(`Failed to fetch product ${id}:`, response.status, response.statusText);
      return null;
    }
    
    const data = await response.json();
    return data.product || null;
  } catch (error) {
    console.error('Error fetching product:', error);
    return null;
  }
}

export async function getProductsByCategory(category: string): Promise<Product[]> {
  try {
    const baseUrl = process.env.NEXT_PUBLIC_BASE_URL || 'http://localhost:5000';
    const response = await fetch(`${baseUrl}/api/products?category=${category}&limit=100`, {
      cache: 'no-store'
    });
    
    if (!response.ok) {
      return [];
    }
    
    const data = await response.json();
    return data.products || [];
  } catch (error) {
    console.error('Error fetching products by category:', error);
    return [];
  }
}

export function getProductsByCategorySync(category: string): Product[] {
  return products.filter(product => product.category === category);
}

export function getProductsBySubCategory(subCategory: string): Product[] {
  return products.filter(product => product.subCategory === subCategory);
}

export function searchProducts(query: string): Product[] {
  const lowerQuery = query.toLowerCase();
  return products.filter(product =>
    product.name.toLowerCase().includes(lowerQuery) ||
    product.description.toLowerCase().includes(lowerQuery) ||
    product.keywords.some(keyword => keyword.toLowerCase().includes(lowerQuery)) ||
    product.seoKeywords.some(keyword => keyword.toLowerCase().includes(lowerQuery))
  );
}

export async function getRelatedProducts(productId: string, limit: number = 4): Promise<Product[]> {
  try {
    // First get the product to find its category/subcategory
    const product = await getProductById(productId);
    if (!product) return [];

    // Fetch related products from the database
    const baseUrl = process.env.NEXT_PUBLIC_BASE_URL || 'http://localhost:5000';
    const response = await fetch(`${baseUrl}/api/products?category=${product.category}&limit=${limit + 1}`, {
      cache: 'no-store'
    });
    
    if (!response.ok) {
      return [];
    }
    
    const data = await response.json();
    const allProducts = data.products || [];
    
    // Filter out the current product and limit results
    return allProducts
      .filter((p: Product) => p.id !== productId)
      .slice(0, limit);
  } catch (error) {
    console.error('Error fetching related products:', error);
    return [];
  }
}
